#!/usr/bin/env python3
"""Generate documentation from the tool catalog.

``catalog/tools.yaml`` is the single source of truth, so the per-tool docs are
generated from it rather than written by hand. Run this after editing the
catalog, and commit the result:

    python tools/gen_docs.py

It writes:

* docs/TOOLS.md          - one page with every tool, grouped by category
* docs/tools/<id>.md     - a page per tool (prerequisites, usage, examples)
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import server.catalog as catalog  # noqa: E402

DOCS = ROOT / "docs"
TOOLS_DOCS = DOCS / "tools"

HEADER = """<!-- Generated by tools/gen_docs.py. Do not edit by hand. -->
<!-- Edit catalog/tools.yaml and re-run the generator instead. -->

"""


def _danger_note(tool: dict) -> str:
    danger = str(tool.get("danger") or "low").lower()
    if danger == "high":
        return "**High impact.** This tool can disrupt a target or a network. Confirm scope first."
    if danger == "moderate":
        return "**Moderate impact.** It touches the target directly; keep the scope tight."
    return "**Low impact.** Reading public information or local files."


def tool_page(tool: dict) -> str:
    lines = [HEADER, f"# {tool.get('name')}\n"]
    lines.append(f"`{tool.get('id')}` &middot; _{tool.get('category')}_\n")
    lines.append(f"{tool.get('summary', '')}\n")
    lines.append(_danger_note(tool) + "\n")

    lines.append("## What this tool needs\n")
    prereqs = tool.get("prerequisites") or ["Nothing beyond the app itself."]
    for item in prereqs:
        lines.append(f"- {item}")
    lines.append("")

    lines.append("## How to use it\n")
    lines.append(str(tool.get("usage", "")).strip() + "\n")

    examples = tool.get("examples") or []
    if examples:
        lines.append("## Examples\n")
        lines.append("```console")
        for example in examples:
            lines.append(f"$ {example}")
        lines.append("```")
        lines.append("")

    packages = tool.get("packages") or []
    install_line = (
        "`apt install " + " ".join(packages) + "`" if packages else "built into the app"
    )
    lines.append("## At a glance\n")
    lines.append(f"- Category: `{tool.get('category')}`")
    lines.append(f"- Install with: {install_line}")
    lines.append(f"- Baseline: {'yes' if tool.get('baseline') else 'no'}")
    lines.append(f"- Licence: {tool.get('license', 'see upstream')}")
    lines.append(f"- Upstream: <{tool.get('homepage', '')}>")
    lines.append("")
    return "\n".join(lines)


def index_page(catalog_data: dict) -> str:
    categories = catalog.categories()
    tools = catalog.tools()
    lines = [HEADER, "# Tool catalog\n"]
    lines.append("Every tool below is documented with its prerequisites and usage. "
                 "Nothing is preinstalled except the small baseline set; everything "
                 "else is installed on demand from inside the app.\n")
    lines.append(f"_{len(tools)} tools in {len(categories)} categories._\n")

    lines.append("## Contents\n")
    for cat in categories:
        members = [t for t in tools if t.get("category") == cat["id"]]
        if not members:
            continue
        lines.append(f"- **{cat['name']}**")
        for tool in members:
            lines.append(f"  - [{tool.get('name')}](tools/{tool.get('id')}.md) "
                         f"- {tool.get('summary', '')}")
    lines.append("")

    lines.append("## Summary table\n")
    lines.append("| Tool | Category | Baseline | Packages | Impact |")
    lines.append("| --- | --- | --- | --- | --- |")
    for tool in tools:
        packages = ", ".join(tool.get("packages") or []) or "built-in"
        lines.append(
            f"| {tool.get('name')} | {tool.get('category')} | "
            f"{'yes' if tool.get('baseline') else 'no'} | {packages} | "
            f"{tool.get('danger', 'low')} |"
        )
    lines.append("")
    lines.append("---\n")
    lines.append("Use only on systems you own or have explicit written authorisation "
                 "to test. See [ACCEPTABLE_USE.md](ACCEPTABLE_USE.md).\n")
    return "\n".join(lines)


def _write(path: Path, text: str) -> None:
    """Write a file with LF endings so generated docs are identical on any OS."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def main() -> int:
    catalog._load.cache_clear()  # make sure we read the current file
    data = {"app": catalog.app_meta(), "tools": catalog.tools()}
    DOCS.mkdir(parents=True, exist_ok=True)
    TOOLS_DOCS.mkdir(parents=True, exist_ok=True)

    _write(DOCS / "TOOLS.md", index_page(data))
    written = 0
    for tool in catalog.tools():
        _write(TOOLS_DOCS / f"{tool.get('id')}.md", tool_page(tool))
        written += 1

    print(f"wrote docs/TOOLS.md and {written} pages under docs/tools/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
